# Depois de escolhida a tag, separa pelo texto (anatomia do ombro x do cotovelo).
REFINO = {'ombro-cotovelo': [('Anatomia do ombro', 'Anatomia do cotovelo', 'cotovelo|olecrano|epicondil|radio proximal|ulna proximal|coronoide|antebraco')]}


def normalizar(texto: str) -> str:
    return unicodedata.normalize("NFKD", texto or "").encode("ascii", "ignore").decode().lower()


def etiquetar(tema: str, enunciado: str, certa: str = "", comentario: str = "") -> list[str]:
    """Uma tag (ou duas, quando empatam de perto) para uma questão do tema."""
    regras = TAGS[tema]
    enun, cert, conc = normalizar(enunciado), normalizar(certa), normalizar(comentario)
    pontos = {}
    for i, (nome, expr) in enumerate(regras):
        if not expr:
            continue
        r = re.compile(expr)
        p = 3 * bool(r.search(enun)) + 3 * bool(r.search(cert)) + bool(r.search(conc))
        if nome.startswith("Outr"):
            p *= 0.5
        if p:
            pontos[nome] = (p, i)
    melhores = sorted(pontos.items(), key=lambda x: (-x[1][0], x[1][1]))
    # O resto é a tag "Outros ..." sem expressão (em mão há também "Outras malformações", que tem).
    resto = next((n for n, e in regras if n.startswith("Outr") and not e), next((n for n, _ in regras if n.startswith("Outr")), regras[-1][0]))
    if not melhores or melhores[0][1][0] < 3:
        tags = [resto]
    else:
        tags = [melhores[0][0]]
        if len(melhores) > 1 and melhores[1][1][0] >= 3 and melhores[1][1][0] >= 0.75 * melhores[0][1][0]:
            tags.append(melhores[1][0])
    for de, para, expr in REFINO.get(tema, []):
        if de in tags and re.search(expr, enun + " " + cert):
            tags = [para if t == de else t for t in tags]
    return list(dict.fromkeys(tags))
