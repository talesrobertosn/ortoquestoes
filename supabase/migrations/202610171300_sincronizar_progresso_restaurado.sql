-- Migração: espelho da parte 30 em supabase/colar-no-painel/ (sincronização das respostas, 17/10/2026).
--
-- Sintoma: desde 17/10 de madrugada, aparelhos mostram "Não foi possível sincronizar" com o motivo
-- 428C9 · column "versao" can only be updated to DEFAULT. Questões novas até subiam, mas qualquer
-- atualização de uma linha existente (responder de novo, revisão, resumo) derrubava o lote inteiro,
-- e o lote ficava preso no aparelho: o painel mostrava zero questões e a pessoa fora dos "ativos hoje".
--
-- A função do repositório só faz `versao = default`, que é aceito; a do banco estava diferente
-- (ou havia um gatilho na tabela). Esta parte:
-- 1. lista, antes, os gatilhos de progresso_usuario (só para conferência; não apaga nenhum);
-- 2. a coluna versao passa de "generated always" para "generated by default": a mesma sequência,
--    os mesmos números e a mesma unicidade, mas o banco deixa de recusar a atualização da versão
--    (é exatamente o erro 428C9). Nenhuma linha muda;
-- 3. recria sincronizar_progresso exatamente como no repositório (testada em Postgres 16:
--    criar e atualizar a mesma linha, com versão nova a cada gravação).
-- Não altera dados. Pode rodar de novo. No fim, mostra a versão do Postgres e a definição da função, para conferência. Depois de colar, os aparelhos enviam o que ficou guardado
-- sozinhos na próxima tentativa (ou ao tocar em "Sincronizar agora").

-- 1. Gatilhos na tabela (deve vir vazio; se vier algo, mande um print).
select tgname as gatilho, pg_get_triggerdef(oid) as definicao
from pg_trigger where tgrelid = 'public.progresso_usuario'::regclass and not tgisinternal;

begin;

alter table public.progresso_usuario alter column versao set generated by default;

create or replace function public.sincronizar_progresso(alteracoes jsonb)
returns setof public.progresso_usuario
language plpgsql security definer set search_path = '' as $$
declare
  dono uuid := auth.uid();
  entrada jsonb;
  atual public.progresso_usuario;
  base bigint;
  id_operacao uuid;
begin
  if dono is null then raise exception 'Autenticação necessária' using errcode = '42501'; end if;
  if jsonb_typeof(alteracoes) <> 'array' or jsonb_array_length(alteracoes) > 100 then
    raise exception 'Lote inválido';
  end if;
  -- Serializa os lotes da mesma conta; outras contas continuam independentes.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(dono::text, 0));
  for entrada in select value from jsonb_array_elements(alteracoes) loop
    if not (entrada ?& array['tipo','item','valor','base','operacao']) then raise exception 'Alteração incompleta'; end if;
    base := (entrada->>'base')::bigint;
    id_operacao := (entrada->>'operacao')::uuid;
    if base is null or base < 0 then raise exception 'Versão inválida'; end if;
    select * into atual from public.progresso_usuario
      where usuario_id = dono and tipo = entrada->>'tipo' and item = entrada->>'item' for update;
    if not found then
      if base <> 0 then raise exception 'Versão inicial inválida'; end if;
      insert into public.progresso_usuario (usuario_id, tipo, item, valor, operacao)
        values (dono, entrada->>'tipo', entrada->>'item', entrada->'valor', id_operacao) returning * into atual;
    elsif atual.operacao = id_operacao then
      null; -- Resposta de rede perdida: repetir a mesma operação não grava outra vez.
    elsif atual.versao = base then
      update public.progresso_usuario set valor = entrada->'valor', operacao = id_operacao,
        versao = default, atualizado_em = now()
        where usuario_id = dono and tipo = entrada->>'tipo' and item = entrada->>'item' returning * into atual;
    end if;
    -- No conflito, devolve a versão corrente sem sobrescrever nenhuma informação.
    return next atual;
  end loop;
end;
$$;
revoke all on function public.sincronizar_progresso(jsonb) from public, anon;
grant execute on function public.sincronizar_progresso(jsonb) to authenticated;

commit;

-- Conferência: versão do Postgres e tipo da coluna (deve aparecer 'd' = by default).
select version() as postgres, (select attidentity from pg_attribute where attrelid = 'public.progresso_usuario'::regclass and attname = 'versao') as identidade_versao;
